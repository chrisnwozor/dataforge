import type { ConnectionPool, Request, config as SqlConfig } from "mssql";
import type { CompiledQuery } from "@/lib/semantic/query/types";
import type { SqlParameter } from "@/lib/semantic/types";
import { connectionConfig, type SqlConnectionSettings } from "./connection";

interface ReservablePool extends ConnectionPool {
  config: SqlConfig;
  collation: unknown;
  acquire(requester: unknown): Promise<unknown>;
  release(connection: unknown): void;
}
type RequestConstructor = new (
  parent: ConnectionPool,
  overrides?: { requestTimeout: number },
) => Request;

export class QueryAbortedError extends Error {
  constructor() {
    super("The query was cancelled.");
    this.name = "QueryAbortedError";
  }
}

function checkAbort(signal?: AbortSignal): void {
  if (signal?.aborted) throw new QueryAbortedError();
}

function bindParameter(
  request: Request,
  sql: typeof import("mssql"),
  parameter: SqlParameter,
): void {
  // Names are generated by the compiler, never passed through from a request.
  if (!/^[_A-Za-z][_A-Za-z0-9]{0,127}$/.test(parameter.name))
    throw new Error("Invalid generated parameter name.");
  const value = parameter.value;
  if (typeof value === "number" && !Number.isFinite(value))
    throw new Error("A query parameter is not a finite number.");
  if (parameter.type === "date" && value !== null) {
    const date = new Date(String(value));
    if (!Number.isFinite(date.getTime()))
      throw new Error("Invalid date parameter.");
    request.input(parameter.name, sql.DateTime2, date);
  } else if (parameter.type === "boolean" || typeof value === "boolean")
    request.input(parameter.name, sql.Bit, value);
  else if (parameter.type === "number" || typeof value === "number")
    request.input(
      parameter.name,
      typeof value === "number" && Number.isSafeInteger(value)
        ? sql.BigInt
        : sql.Float,
      value,
    );
  else request.input(parameter.name, sql.NVarChar(sql.MAX), value);
}

/**
 * Only server-produced query compiler output reaches this transport. It has no
 * text-taking route or batch API. Reserve the same tedious connection contract
 * used by the load runner, then release it after the single SELECT settles.
 */
export async function executeCompiledQuery(
  settings: SqlConnectionSettings,
  compiled: CompiledQuery,
  signal?: AbortSignal,
): Promise<Record<string, unknown>[]> {
  checkAbort(signal);
  const { default: sql } = await import("mssql");
  checkAbort(signal);
  const config = connectionConfig(settings, 30_000);
  config.pool = { ...config.pool, max: 1, min: 1 };
  const pool = new sql.ConnectionPool(config) as ReservablePool;
  pool.on("error", () => {});
  let physical: unknown;
  let active: Request | undefined;
  const abort = () => active?.cancel();
  signal?.addEventListener("abort", abort, { once: true });
  try {
    await pool.connect();
    checkAbort(signal);
    physical = await pool.acquire(pool);
    checkAbort(signal);
    const parent = {
      connected: true,
      config: pool.config,
      collation: pool.collation,
      acquire(
        _request: unknown,
        callback: (
          error: Error | null,
          connection: unknown,
          config: SqlConfig,
        ) => void,
      ) {
        process.nextTick(callback, null, physical, pool.config);
      },
      release() {},
    } as unknown as ConnectionPool;
    const RequestClass = sql.Request as unknown as RequestConstructor;
    const request = new RequestClass(parent, { requestTimeout: 30_000 });
    active = request;
    for (const parameter of compiled.params)
      bindParameter(request, sql, parameter);
    checkAbort(signal);
    const result = await request.query<Record<string, unknown>>(compiled.sql);
    checkAbort(signal);
    return result.recordset;
  } catch (error) {
    if (signal?.aborted) throw new QueryAbortedError();
    throw error;
  } finally {
    signal?.removeEventListener("abort", abort);
    active = undefined;
    if (physical) pool.release(physical);
    await pool.close().catch(() => {});
  }
}
